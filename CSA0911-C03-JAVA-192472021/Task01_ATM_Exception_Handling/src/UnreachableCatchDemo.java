package task01;

import java.io.FileNotFoundException;

/**
 * Task 01 - Student B Evidence:
 * Demonstrating Unreachable Catch Block Compilation Error.
 *
 * In Java, catch blocks must be ordered from most specific (subclass)
 * to most general (superclass). If a broader catch block like `catch (Exception e)`
 * appears before `catch (FileNotFoundException e)`, the compiler issues an error:
 * "unreachable code" or "exception FileNotFoundException has already been caught".
 */
public class UnreachableCatchDemo {

    public static void main(String[] args) {
        System.out.println("==================================================");
        System.out.println("   DEMONSTRATING UNREACHABLE CATCH BLOCK          ");
        System.out.println("   Student B Evidence - Compilation Rule          ");
        System.out.println("==================================================");

        demonstrateCorrectOrdering();
        explainUnreachableError();
    }

    public static void demonstrateCorrectOrdering() {
        System.out.println("\n--- Correct Catch Block Hierarchy (Narrower to Broader) ---");
        try {
            simulateError();
        } catch (FileNotFoundException fnf) {
            System.out.println("[Handled by specific subclass]: FileNotFoundException caught.");
        } catch (Exception e) {
            System.out.println("[Handled by general superclass]: Generic Exception caught.");
        }
    }

    public static void explainUnreachableError() {
        System.out.println("\n--- Why Broader Before Narrower Fails To Compile ---");
        System.out.println("If we write the following code in Java:");
        System.out.println("    try {");
        System.out.println("        simulateError();");
        System.out.println("    } catch (Exception e) {          // Superclass catch");
        System.out.println("        System.out.println(\"Generic\");");
        System.out.println("    } catch (FileNotFoundException fnf) { // Subclass catch - UNREACHABLE!");
        System.out.println("        System.out.println(\"Specific\");");
        System.out.println("    }");
        System.out.println("\nCompiler Error generated by javac:");
        System.out.println("    error: exception FileNotFoundException has already been caught");
        System.out.println("Reason: Any FileNotFoundException object is an instance of Exception.");
        System.out.println("The JVM matches catch clauses top-to-bottom. The first block will match");
        System.out.println("every instance, making the second block completely dead (unreachable) code.");
    }

    private static void simulateError() throws FileNotFoundException {
        throw new FileNotFoundException("Simulated missing card reader hardware file.");
    }
}
